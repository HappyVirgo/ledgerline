// Command loadgen drives synthetic payment traffic through an in-process ledgerline
// server over loopback HTTP and reports throughput and latency percentiles.
//
// Each "payment" is an idempotent create followed by a capture. The card mix is
// deterministic (every 20th payment is declined), so runs are comparable. After the
// run it checks ledger invariants and reconciles a synthetic settlement file with
// injected discrepancies.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"net/http"
	"net/http/httptest"
	"os"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
	"sync"
	"time"

	"github.com/HappyVirgo/ledgerline/internal/api"
	"github.com/HappyVirgo/ledgerline/internal/ledger"
	"github.com/HappyVirgo/ledgerline/internal/payments"
	"github.com/HappyVirgo/ledgerline/internal/processor"
	"github.com/HappyVirgo/ledgerline/internal/store"
	"github.com/HappyVirgo/ledgerline/internal/tenant"
)

type result struct {
	latency  time.Duration
	captured bool
	ref      string
	tenant   int
	err      error
}

func main() {
	total := flag.Int("n", 5000, "number of payments")
	workers := flag.Int("workers", 8, "concurrent clients")
	tenants := flag.Int("tenants", 4, "number of tenants (workers are spread across them)")
	dbMode := flag.String("db", "file", "\"file\" (temp SQLite file, WAL) or \"memory\"")
	out := flag.String("out", "", "write a markdown report to this path")
	flag.Parse()
	if err := run(*total, *workers, *tenants, *dbMode, *out); err != nil {
		fmt.Fprintln(os.Stderr, "loadgen:", err)
		os.Exit(1)
	}
}

func run(total, workers, nTenants int, dbMode, out string) error {
	path := ":memory:"
	if dbMode == "file" {
		dir, err := os.MkdirTemp("", "ledgerline-load")
		if err != nil {
			return err
		}
		defer os.RemoveAll(dir)
		path = filepath.Join(dir, "load.db")
	}
	db, err := store.Open(path)
	if err != nil {
		return err
	}
	defer db.Close()

	ctx := context.Background()
	keys := make([]string, nTenants)
	ids := make([]string, nTenants)
	for i := range keys {
		if ids[i], keys[i], err = tenant.Create(ctx, db, fmt.Sprintf("Synthetic Tenant %d", i)); err != nil {
			return err
		}
	}
	srv := &api.Server{DB: db, Payments: &payments.Service{DB: db, Proc: processor.NewMock()},
		Limiter: tenant.NewRateLimiter(1e9, 1e9)}
	ts := httptest.NewServer(srv.Handler())
	defer ts.Close()
	client := ts.Client()
	client.Transport.(*http.Transport).MaxIdleConnsPerHost = workers

	jobs := make(chan int)
	results := make(chan result, total)
	var wg sync.WaitGroup
	start := time.Now()
	for w := 0; w < workers; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range jobs {
				results <- onePayment(client, ts.URL, keys[i%nTenants], i%nTenants, i)
			}
		}()
	}
	for i := 0; i < total; i++ {
		jobs <- i
	}
	close(jobs)
	wg.Wait()
	elapsed := time.Since(start)
	close(results)

	var lat []time.Duration
	settlements := make([]strings.Builder, nTenants)
	captured, declined, failed := 0, 0, 0
	for r := range results {
		switch {
		case r.err != nil:
			failed++
			fmt.Fprintln(os.Stderr, "payment error:", r.err)
			continue
		case r.captured:
			captured++
		default:
			declined++
		}
		lat = append(lat, r.latency)
		if r.captured {
			writeSettlement(&settlements[r.tenant], r.ref, captured)
		}
	}
	slices.Sort(lat)

	for _, id := range ids {
		if err := ledger.Verify(ctx, db, id); err != nil {
			return fmt.Errorf("ledger invariant violated: %w", err)
		}
	}
	reconStart := time.Now()
	var matched, missing, mismatched int
	for i := range keys {
		rep, err := reconcile(client, ts.URL, keys[i], settlements[i].String())
		if err != nil {
			return err
		}
		matched += rep.Matched
		missing += len(rep.Missing)
		mismatched += len(rep.Mismatched)
	}
	reconDur := time.Since(reconStart)

	report := fmt.Sprintf(`# ledgerline load test

Generated by `+"`go run ./cmd/loadgen`"+` on %s.

- Machine: %s, %s/%s, %d logical CPUs, %s
- Database: SQLite (%s mode, single connection), mock processor, in-process server over loopback HTTP
- Workload: %d synthetic payments (create with Idempotency-Key + capture), %d concurrent clients, %d tenants

| metric | value |
|---|---|
| payments/sec (create+capture) | %.0f |
| p50 latency | %s |
| p95 latency | %s |
| p99 latency | %s |
| captured / declined / errors | %d / %d / %d |
| ledger.Verify across tenants | passed |
| reconciliation (matched / missing / mismatched) | %d / %d / %d |
| reconciliation time for all tenants | %s |

Settlement files are synthetic: every 50th captured payment is omitted and every 75th
is reported with an amount 1 unit short, so missing/mismatched counts are expected.
`, time.Now().Format("2006-01-02"), cpuName(), runtime.GOOS, runtime.GOARCH, runtime.NumCPU(), runtime.Version(),
		dbMode, total, workers, nTenants,
		float64(captured+declined)/elapsed.Seconds(), pct(lat, 0.50), pct(lat, 0.95), pct(lat, 0.99),
		captured, declined, failed, matched, missing, mismatched, reconDur.Round(time.Millisecond))
	fmt.Print(report)
	if out != "" {
		if err := os.WriteFile(out, []byte(report), 0o644); err != nil {
			return err
		}
	}
	if failed > 0 {
		return fmt.Errorf("%d payments failed", failed)
	}
	return nil
}

// writeSettlement appends a settlement line, injecting deterministic discrepancies.
func writeSettlement(b *strings.Builder, ref string, n int) {
	if b.Len() == 0 {
		b.WriteString("processor_ref,amount,currency\n")
	}
	switch {
	case n%50 == 0:
		return // missing from settlement
	case n%75 == 0:
		fmt.Fprintf(b, "%s,%d,USD\n", ref, amount-1)
	default:
		fmt.Fprintf(b, "%s,%d,USD\n", ref, amount)
	}
}

const amount = 1999

func onePayment(c *http.Client, base, key string, tenantIdx, i int) result {
	card := processor.CardApproved
	if i%20 == 19 {
		card = processor.CardDeclined
	}
	body := fmt.Sprintf(`{"amount":%d,"currency":"USD","card_number":%q}`, amount, card)
	start := time.Now()
	var in payments.Intent
	status, err := call(c, key, base+"/v1/payment_intents", fmt.Sprintf("load-%d", i), body, &in)
	if err != nil {
		return result{err: err}
	}
	if status == http.StatusPaymentRequired {
		return result{latency: time.Since(start)}
	}
	if status != http.StatusCreated {
		return result{err: fmt.Errorf("create: status %d", status)}
	}
	if status, err = call(c, key, base+"/v1/payment_intents/"+in.ID+"/capture", "", "", &in); err != nil || status != 200 {
		return result{err: fmt.Errorf("capture: status %d err %v", status, err)}
	}
	return result{latency: time.Since(start), captured: true, ref: in.CaptureRef, tenant: tenantIdx}
}

func call(c *http.Client, key, url, idem, body string, out any) (int, error) {
	req, err := http.NewRequest(http.MethodPost, url, bytes.NewBufferString(body))
	if err != nil {
		return 0, err
	}
	req.Header.Set("Authorization", "Bearer "+key)
	if idem != "" {
		req.Header.Set(api.IdempotencyHeader, idem)
	}
	resp, err := c.Do(req)
	if err != nil {
		return 0, err
	}
	defer resp.Body.Close()
	return resp.StatusCode, json.NewDecoder(resp.Body).Decode(out)
}

type reconReport struct {
	Matched    int               `json:"matched"`
	Missing    []json.RawMessage `json:"missing_from_settlement"`
	Mismatched []json.RawMessage `json:"mismatched"`
}

func reconcile(c *http.Client, base, key, csv string) (reconReport, error) {
	var rep reconReport
	status, err := call(c, key, base+"/v1/reconciliations", "", csv, &rep)
	if err == nil && status != 200 {
		err = fmt.Errorf("reconcile: status %d", status)
	}
	return rep, err
}

func pct(sorted []time.Duration, p float64) time.Duration {
	if len(sorted) == 0 {
		return 0
	}
	idx := int(float64(len(sorted))*p+0.5) - 1
	idx = max(0, min(idx, len(sorted)-1))
	return sorted[idx].Round(time.Microsecond)
}

// cpuName returns a best-effort CPU model string.
func cpuName() string {
	if b, err := os.ReadFile("/proc/cpuinfo"); err == nil {
		for _, line := range strings.Split(string(b), "\n") {
			if k, v, ok := strings.Cut(line, ":"); ok && strings.TrimSpace(k) == "model name" {
				return strings.TrimSpace(v)
			}
		}
	}
	if v := os.Getenv("PROCESSOR_IDENTIFIER"); v != "" {
		return v
	}
	return "unknown CPU"
}
